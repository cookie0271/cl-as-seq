def set_trainable_modules(
        model,
        train_backbone=False,
        train_corr=True,
        train_gate=True,
        train_adapter=False,
        train_lora=False,
        train_bitfit=False,
        train_head=True,
        partial_freeze_mode='none',
        train_last_tf_layers=0,
        freeze_encoder=False,
        random_match_target_trainable_params=None,
        random_match_seed=0,
        random_match_scope='tf_only',
        random_match_unit='layer_or_block',
        random_match_target_last_tf_layers=2,
        adapter_dim=None,
        adapter_layers='last2',
        adapter_location='post_layer',
        lora_rank=None,
        lora_alpha=16,
        lora_dropout=0.0,
        lora_layers='all',
        lora_target_modules='attn_only',
        lora_strict_match=False,
        lora_rank_candidates=None,
        bitfit_scope='transformer_only',
        bitfit_include_layernorm_bias=True,
        bitfit_include_head_bias=True,
        bitfit_strict_match=False,
        target_trainable_params=None):
    if hasattr(model, 'set_trainable_modules'):
        model.set_trainable_modules(
            train_backbone=train_backbone,
            train_corr=train_corr,
            train_gate=train_gate,
            train_bitfit=train_bitfit,
            train_adapter=train_adapter,
            train_lora=train_lora,
            train_head=train_head,
            partial_freeze_mode=partial_freeze_mode,
            train_last_tf_layers=train_last_tf_layers,
            freeze_encoder=freeze_encoder,
            random_match_target_trainable_params=random_match_target_trainable_params,
            random_match_seed=random_match_seed,
            random_match_scope=random_match_scope,
            random_match_unit=random_match_unit,
            random_match_target_last_tf_layers=random_match_target_last_tf_layers,
            adapter_dim=adapter_dim,
            adapter_layers=adapter_layers,
            adapter_location=adapter_location,
            lora_rank=lora_rank,
            lora_alpha=lora_alpha,
            lora_dropout=lora_dropout,
            lora_layers=lora_layers,
            lora_target_modules=lora_target_modules,
            lora_strict_match=lora_strict_match,
            lora_rank_candidates=lora_rank_candidates,
            bitfit_scope=bitfit_scope,
            bitfit_include_layernorm_bias=bitfit_include_layernorm_bias,
            bitfit_include_head_bias=bitfit_include_head_bias,
            bitfit_strict_match=bitfit_strict_match,
            target_trainable_params=target_trainable_params,
        )
    return model